"""Workload analysis: writes figures and a markdown summary of the numbers quoted in the report.

    python -m cwfc.eda --data challenge_data --output reports

Statistics that inform modelling choices (hourly profile, autocorrelation) are computed on
the training window only; descriptive statistics of the whole release are labelled as such.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from cwfc.data import HOLDOUT_STEPS, build_panel, load_metadata, load_readings, split_index
from cwfc.forecasters import make_history, seasonal_profile

SEGMENTS = ["vm_category", "virtual_core_bucket", "memory_gb_bucket"]


def acf(x: np.ndarray, lag: int) -> float:
    """How similar the series is to itself shifted by `lag` steps (1 = same, 0 = unrelated)."""
    x = x - x.mean()
    return float(np.sum(x[lag:] * x[:-lag]) / np.sum(x * x))


def main(argv: list[str] | None = None) -> None:
    """Command line entry: describe the data and write eda_summary.md plus the overview figures."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", default="challenge_data", type=Path)
    parser.add_argument("--output", default="reports", type=Path)
    args = parser.parse_args(argv)
    fig_dir = args.output / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)

    raw = load_readings(args.data)
    meta = load_metadata(args.data)
    panel = build_panel(raw)
    targets = panel.targets()
    split = split_index(len(targets), HOLDOUT_STEPS)
    cpu = panel.cpu
    hours = (panel.timestamps - panel.timestamps[0]) / 3600
    meta = meta.set_index("vm_id").reindex(panel.vm_ids)
    md = ["# Workload analysis (generated by `python -m cwfc.eda`)", ""]

    # --- data quality and coverage -----------------------------------------------------
    md += ["## Data quality", "", *(f"- {k}: {v}" for k, v in panel.quality.items())]
    md += [
        f"- readings with min_cpu <= avg_cpu <= max_cpu violated: "
        f"{int(((raw.min_cpu > raw.avg_cpu + 1e-9) | (raw.avg_cpu > raw.max_cpu + 1e-9)).sum())}",
        f"- observations per VM: min {int((~np.isnan(cpu)).sum(1).min())}, max {int((~np.isnan(cpu)).sum(1).max())}",
        f"- active_vm_count over all timestamps: min {targets.active_vm_count.min()}, max {targets.active_vm_count.max()}",
        f"- metadata rows {len(meta)}, VMs without metadata {int(meta['vm_category'].isna().sum())}",
        "",
        "## Lifetimes and churn (metadata, 30-day upstream trace)",
        "",
        f"- timestamp_vm_created: min {meta.timestamp_vm_created.min()}, max {meta.timestamp_vm_created.max()} "
        "(all VMs already running at trace start: left-censored)",
        f"- deleted before the 30-day trace end (2,591,400 s): {int((meta.timestamp_vm_deleted < meta.timestamp_vm_deleted.max()).sum())} VMs",
        f"- deleted inside the 11.1 h window: {int((meta.timestamp_vm_deleted <= panel.timestamps[-1]).sum())}",
        f"- observed lifetime quantiles (h, 10/25/50%): "
        f"{np.round(np.quantile((meta.timestamp_vm_deleted - meta.timestamp_vm_created) / 3600, [.1, .25, .5]), 1).tolist()}",
        "",
    ]

    # --- utilization distribution ------------------------------------------------------
    vm_mean = np.nanmean(cpu, axis=1)
    order = np.sort(vm_mean)[::-1]
    md += [
        "## CPU utilization distribution (all 134 steps)",
        "",
        f"- reading-level avg_cpu quantiles 10/50/90/99%: {np.round(np.nanquantile(cpu, [.1, .5, .9, .99]), 2).tolist()}",
        f"- per-VM mean quantiles 10/50/90/99%: {np.round(np.quantile(vm_mean, [.1, .5, .9, .99]), 2).tolist()}",
        f"- top 10% of VMs carry {order[: len(order) // 10].sum() / order.sum():.1%} of total CPU",
        f"- VMs with window mean < 5%: {(vm_mean < 5).mean():.1%}; > 50%: {(vm_mean > 50).mean():.1%}",
        f"- share of readings > 80% per timestamp: {np.round(np.nanmean(cpu > 80, axis=0).min(), 4)}-{np.round(np.nanmean(cpu > 80, axis=0).max(), 4)}",
        f"- corr(window mean, metadata lifetime avg_cpu): {np.corrcoef(vm_mean, meta.avg_cpu)[0, 1]:.3f} "
        "(metadata CPU stats summarise 30 days, so they contain future information: excluded from features)",
        "",
    ]

    # --- temporal structure (training window only) ---------------------------------------
    y = targets.aggregate_cpu_utilization.to_numpy()
    tr = y[:split]
    hist = make_history(panel.timestamps[:split], tr, panel.step)
    prof = seasonal_profile(hist)
    d = np.diff(tr)
    vm_lag12 = []
    for row in cpu[:, :split]:
        r = row - np.nanmean(row)
        den = np.nansum(r * r)
        vm_lag12.append(np.nansum(r[12:] * r[:-12]) / den if den > 0 else np.nan)
    md += [
        "## Temporal structure (training window, first 110 steps)",
        "",
        f"- aggregate CPU: mean {tr.mean():.3f}, std {tr.std():.3f}, min {tr.min():.3f} (h {hours[tr.argmin()]:.2f}), max {tr.max():.3f} (h {hours[tr.argmax()]:.2f})",
        f"- ACF of level, lags 1/3/6/12/24: {[round(acf(tr, k), 2) for k in (1, 3, 6, 12, 24)]}",
        f"- ACF of first differences, lags 1/3/12/24/36: {[round(acf(d, k), 2) for k in (1, 3, 12, 24, 36)]}",
        f"- hourly profile (pp, phase 0..11): {np.round(prof, 3).tolist()}; peak-to-trough {prof.max() - prof.min():.3f} pp",
        f"- per-VM lag-12 autocorrelation quantiles 25/50/75%: {np.round(np.nanquantile(vm_lag12, [.25, .5, .75]), 2).tolist()}",
        "",
    ]

    # --- segments ----------------------------------------------------------------------
    md += ["## Segments (all 134 steps)", ""]
    fig, axes = plt.subplots(1, 3, figsize=(15, 4), sharex=True)
    for ax, seg in zip(axes, SEGMENTS):
        labels = meta[seg].astype(str).to_numpy()
        rows = []
        for lab in sorted(set(labels), key=lambda s: (len(s), s)):
            series = np.nanmean(cpu[labels == lab], axis=0)
            rows.append({
                "segment": lab, "vms": int((labels == lab).sum()), "mean_cpu": series.mean(),
                "temporal_std": series.std(), "min": series.min(), "max": series.max(),
                "share_of_cpu": np.nansum(cpu[labels == lab]) / np.nansum(cpu),
            })
            ax.plot(hours, series, label=f"{lab} (n={rows[-1]['vms']})", lw=1)
        ax.axvline(hours[split], color="k", ls=":", lw=1)
        ax.set(title=seg, xlabel="hours since trace start", ylabel="mean avg_cpu (%)")
        ax.legend(fontsize=7)
        md += [f"### {seg}", "", "```", pd.DataFrame(rows).round(3).to_string(index=False), "```", ""]
    plt.tight_layout()
    plt.savefig(fig_dir / "segments.png", dpi=110)
    plt.close()

    # --- transient between hours 4.5 and 6: who drove it? --------------------------------
    base = np.r_[0:54, 75:split]  # steps outside the visible bump, training window only
    bump = np.r_[54:75]
    lift = np.nanmean(cpu[:, bump], axis=1) - np.nanmean(cpu[:, base], axis=1)
    contrib = lift / len(lift)  # contribution of each VM to the aggregate lift
    top = np.argsort(contrib)[::-1]
    by_cat = pd.Series(contrib).groupby(meta["vm_category"].to_numpy()).sum()
    md += [
        "## Transient at hours 4.5-6.25 (steps 54-74)",
        "",
        f"- aggregate lift vs rest of training window: {contrib.sum():.3f} pp",
        f"- top 10 / 50 / 100 VMs explain {contrib[top[:10]].sum() / contrib.sum():.0%} / "
        f"{contrib[top[:50]].sum() / contrib.sum():.0%} / {contrib[top[:100]].sum() / contrib.sum():.0%} of the lift",
        f"- distinct deployments among top 50 VMs: {meta['deployment_id'].iloc[top[:50]].nunique()}",
        f"- lift by category (pp): {by_cat.round(3).to_dict()}",
        "",
    ]

    # --- figures -----------------------------------------------------------------------
    fig, axes = plt.subplots(2, 2, figsize=(13, 8))
    ax = axes[0, 0]
    ax.plot(hours, y, color="k", lw=1)
    ax.axvline(hours[split], color="C3", ls="--", label="train | holdout")
    ax.axvspan(hours[54], hours[74], color="C1", alpha=0.15, label="transient")
    ax.set(title="Aggregate CPU utilization (mean of VM avg_cpu)", xlabel="hours since trace start", ylabel="%")
    ax.legend(fontsize=8)
    ax = axes[0, 1]
    ax.hist(np.log10(np.clip(vm_mean, 1e-2, None)), bins=60, color="0.4")
    ax.set(title="Per-VM mean CPU over the window", xlabel="log10(mean avg_cpu %)", ylabel="VMs")
    ax = axes[1, 0]
    ax.bar(range(len(prof)), prof, color="C0")
    ax.set(title="Hourly profile of aggregate CPU (training window)", xlabel="5-min phase within the hour", ylabel="pp vs hourly trend")
    ax = axes[1, 1]
    lags = range(1, 37)
    ax.bar(lags, [acf(d, k) for k in lags], color="0.4")
    ax.axhline(1.96 / np.sqrt(len(d)), color="C3", ls=":")
    ax.axhline(-1.96 / np.sqrt(len(d)), color="C3", ls=":")
    ax.set(title="ACF of first differences (training window)", xlabel="lag (5-min steps)")
    plt.tight_layout()
    plt.savefig(fig_dir / "overview.png", dpi=110)
    plt.close()

    (args.output / "eda_summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
